% bignum unification test

% 1. Same bignum
big1 :-
    123456789012345678901234567890 =
    123456789012345678901234567890.

% 2. Different bignums (must fail)
big2 :-
    123456789012345678901234567890 =
    123456789012345678901234567891.

% 3. Variable binding
big3(X) :-
    X = 123456789012345678901234567890.

% 4. Dereference
big4(X) :-
    X = Y,
    Y = 123456789012345678901234567890.

% 5. Backtracking
big5(X) :-
    big_value(X).

big_value(123456789012345678901234567890).
big_value(987654321098765432109876543210).
big_value(111111111111111111111111111111).

% 6. Repeated variable
big6(X) :-
    X = 123456789012345678901234567890,
    X = 123456789012345678901234567890.

% 7. Atom vs bignum (must fail)
big7 :-
    abc = 123456789012345678901234567890.

% 8. Small integer vs bignum (must fail)
big8 :-
    123 = 123456789012345678901234567890.

